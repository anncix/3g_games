def is_promotion_locked(level: int) -> bool:
    """当前等级是否处于转职锁经验状态（恰好等于转职节点）"""
    return level in PROMOTION_LEVELS


def exp_needed(level: int) -> int:
    """L → L+1 所需经验（指数缓增，对齐 spec 千万级经验道具量级）"""
    if level >= MAX_LEVEL:
        return 0
    if level < 9:
        # 新手阶段：100-800
        return 100 + 80 * level
    if level < 59:
        # 初级阶段：1k-50k
        return 1000 + 800 * (level - 9)
    if level < 109:
        # 中级阶段：50k-500k
        return 50000 + 8000 * (level - 59)
    if level < 139:
        # 中高级阶段：500k-2M
        return 500000 + 50000 * (level - 109)
    if level < 169:
        # 高级阶段：2M-10M
        return 2000000 + 250000 * (level - 139)
    if level < 189:
        # 顶级阶段：10M-50M
        return 10000000 + 2000000 * (level - 169)
    # 终极阶段：50M+
    return 50000000 + 5000000 * (level - 189)


