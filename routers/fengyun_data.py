# 荣誉系统（spec：击杀不同阵营玩家获荣誉）
# ============================================================
def honor_for_kill(winner_level: int, loser_level: int) -> int:
    """根据双方等级差计算荣誉值。

    - 战胜比自己等级高的角色：15 点
    - 战胜比自己等级低 10 级以内：10 点
    - 战胜比自己等级低 10-20 级：5 点
    - 战胜比自己等级低 20 级以上：0 点
    """
    diff = winner_level - loser_level
    if diff < 0:
        return 15  # 对方等级更高
    if diff <= 10:
        return 10
    if diff <= 20:
        return 5
    return 0


