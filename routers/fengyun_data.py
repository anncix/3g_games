# 装备系统（spec：5 品质 × 7 部位，上千件装备）
# 品质：普通 / 精良 / 卓越 / 史诗 / 神器
# 部位：头/手/衣/腿/鞋/裤子/饰品
# 交易参考价：神器价 = 2×史诗价 = 4×卓越价（同等级）
# ============================================================
EQUIP_QUALITIES = ["普通", "精良", "卓越", "史诗", "神器"]
EQUIP_SLOTS = ["头", "手", "衣", "腿", "鞋", "裤子", "饰品"]

# 品质系数（普通=1.0；神器 = 2×史诗 = 4×卓越）
EQUIP_QUALITY_COEF = {
    "普通": 1.0,
    "精良": 1.5,
    "卓越": 2.0,
    "史诗": 4.0,
    "神器": 8.0,
}

# 部位主属性基础值（普通品质 1 级装备）
EQUIP_SLOT_BASE = {
    "头":   {"hp_bonus": 20, "def_bonus": 5},
    "手":   {"atk_bonus": 5, "def_bonus": 2},
    "衣":   {"hp_bonus": 40, "def_bonus": 8},
    "腿":   {"dodge_bonus": 4, "def_bonus": 3},
    "鞋":   {"dodge_bonus": 6, "hp_bonus": 10},
    "裤子": {"hp_bonus": 30, "def_bonus": 6},
    "饰品": {"atk_bonus": 8, "crit_bonus": 3},
}


def gen_equip_stats(slot: str, quality: str, level_req: int) -> dict:
    """按 spec 价值体系生成装备属性。"""
    base = EQUIP_SLOT_BASE.get(slot, {"atk_bonus": 5})
    coef = EQUIP_QUALITY_COEF[quality]
    lvl_factor = 1.0 + (level_req - 1) * 0.15
    out = {}
    for k, v in base.items():
        out[k] = int(v * coef * lvl_factor)
    return out


def gen_equip_price(quality: str, level_req: int) -> int:
    """按 spec 交易参考价规则（神器 = 2×史诗 = 4×卓越，同等级）。"""
    base = 100 * (1 + (level_req - 1) * 0.2)
    return int(base * EQUIP_QUALITY_COEF[quality])


