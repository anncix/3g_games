# 剧情弧进度统计辅助
def arc_progress(arc, module_quests_map: dict) -> tuple[int, int]:
    """返回 (已完成主线数, 总主线数)。module_quests_map: {key: (done, total)}"""
    done = total = 0
    for key in arc[3]:
        d, t = module_quests_map.get(key, (0, 0))
        done += d
        total += t
    return done, total


# ============================================================
# 六、完成度统计（供 /story 总览）
# ============================================================
def feature_stats() -> dict:
    """统计家园底座功能完成度。"""
    total = done = 0
    for _, _, _, _, feats in HOME_BASE_FEATURES:
        for _, _, st in feats:
            total += 1
            if st == "✅":
                done += 1
    return {"home_total": total, "home_done": done,
            "home_pct": round(done / total * 100) if total else 0}
