# 品质属性倍率
QUALITY_MULT = {"白": 1.0, "蓝": 1.4, "紫": 2.0, "金": 3.0, "神": 4.5, "圣": 6.5}

# 部位主属性倾向（生成装备时按此分配属性权重）
SLOT_PRIMARY = {
    "武器": "atk",
    "头盔": "defense",
    "盔甲": "hp",
    "靴子": "speed",
    "戒指": "atk",
    "手镯": "hp",
}


def gen_equip_stats(slot: str, quality: str, level: int) -> dict:
    """按 spec 生成装备属性（白→圣 1.0x→6.5x 倍率）"""
    base = max(1, level)
    mult = QUALITY_MULT[quality]
    if slot == "武器":
        return {"atk_bonus": int(base * 2 * mult), "def_bonus": 0, "hp_bonus": 0, "mp_bonus": int(base * 0.3 * mult)}
    if slot == "头盔":
        return {"atk_bonus": 0, "def_bonus": int(base * 1.2 * mult), "hp_bonus": int(base * 0.5 * mult), "mp_bonus": int(base * 0.5 * mult)}
    if slot == "盔甲":
        return {"atk_bonus": 0, "def_bonus": int(base * 1.5 * mult), "hp_bonus": int(base * 3 * mult), "mp_bonus": 0}
    if slot == "靴子":
        return {"atk_bonus": int(base * 0.3 * mult), "def_bonus": int(base * 0.3 * mult), "hp_bonus": int(base * 0.5 * mult), "mp_bonus": 0}
    if slot == "戒指":
        return {"atk_bonus": int(base * 1.5 * mult), "def_bonus": 0, "hp_bonus": 0, "mp_bonus": int(base * 0.8 * mult)}
    if slot == "手镯":
        return {"atk_bonus": 0, "def_bonus": int(base * 0.8 * mult), "hp_bonus": int(base * 1.5 * mult), "mp_bonus": 0}
    return {"atk_bonus": 0, "def_bonus": 0, "hp_bonus": 0, "mp_bonus": 0}


def gen_equip_price(quality: str, level: int) -> int:
    """装备售价"""
    base = max(1, level)
    mult = QUALITY_MULT[quality]
    return int(50 * base * mult)


