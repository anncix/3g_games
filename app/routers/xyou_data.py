# 战斗公式（spec：回合制，技能/普攻/药品/自动战斗）
# ============================================================
def calc_damage(atk: int, defense: int, mult: float = 1.0) -> int:
    """普攻/技能伤害计算（基础攻击×倍率−防御×0.5）"""
    return max(1, int(atk * mult - defense * 0.5))


def calc_pet_exp(master_exp: int) -> int:
    """宠物经验：人物 20%"""
    return int(master_exp * 0.2)


