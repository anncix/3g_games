    if level < 59:
        # 初级阶段：1k-50k
        return 1000 + 800 * (level - 9)
    if level < 109:
        # 中级阶段：50k-500k
        return 50000 + 8000 * (level - 59)
    if level < 139:
        # 中高级阶段：500k-2M
        return 500000 + 50000 * (level - 109)
